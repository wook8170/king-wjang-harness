/**
 * [PERF-09] **부하 창 판정 — 정의는 한 벌이다.**
 *
 * 시간 문턱을 단정하는 곳이 둘 있다: 벤치(`bench-hook-latency.mjs`)와 회귀 테스트
 * (`fixes-round2-2026-08-27.test.ts` 의 [API-04]). 벤치에는 「지금 이 머신이 바쁜가」를
 * 보는 판정이 있었고 **테스트에는 없었다** — 그래서 같은 제품을 두 곳이 다르게 채점했다.
 * 감사자가 그 차이 때문에 판정을 하루 미루고 유휴 창을 50분 기다렸다([PERF-08] 소동).
 *
 * 목록이 둘이면 언제나 한쪽이 낡는다. 그래서 규칙을 여기 한 곳에 두고 양쪽이 읽는다
 * ([UX-102]·[LOGIC-14] 가 세운 처방과 같다 — 판정은 한 벌, 문구만 표면마다).
 *
 * ## 왜 「그냥 부하에 둔감한 지표」로 바꾸지 않았나 — 세 후보를 실측으로 기각했다
 *
 * 1MB 상한 페이로드로 훅을 돌리며 load 를 함께 기록했다(2026-08-29, 10코어):
 *
 * | 후보 | 유휴(load ~4) | 부하(load 15~51) | 편차 |
 * |---|---|---|---|
 * | wall-time | 4037ms | 30593ms | **7.6배** |
 * | CPU 시간 `user+sys` | — | 9.58s → 16.14s | **1.7배** |
 * | 같은 창 기준값 대비 비율 | — | 8.44 → 31.30 | **3.7배** |
 *
 * **CPU 시간조차 부하에 둔감하지 않다.** 바쁜 머신에서는 한 사이클이 하는 일이 줄어드는데
 * (캐시 경합·메모리 대역·주파수·하이퍼스레드 공유) 사이클 수는 그대로 청구되기 때문이다.
 * 같은 창에서 잰 기준값으로 나눈 «비율»은 오히려 더 흔들렸다. 그러므로 **부하 창에서 쓸 수
 * 있는 대체 단언은 없다.** 벤치가 처음부터 취한 태도가 옳았다 —
 * 「여기서 나온 충족도 충족이 아니다」.
 *
 * 그래서 이 모듈은 **문턱을 낮추지 않는다.** 부하 창에서는 시간 «판정을 하지 않는다»고
 * 말할 뿐이고, 그 사실과 잰 값을 사유로 남긴다. 감추는 것과 다르다: 감추는 것은 조용히
 * 통과시키는 것이고, 이것은 **판정 불가를 판정 불가라고 적는 것**이다.
 */
import * as os from 'node:os';

/**
 * 코어당 이 비율을 넘는 1분 load 면 「바쁘다」. 0.5 는 벤치가 쓰던 값을 그대로 옮긴 것이다
 * — 새 기준을 세우면 지금까지의 벤치 기록과 비교할 수 없게 된다.
 */
export const BUSY_FACTOR = 0.5;

/** 지금 이 머신의 부하 창. `busy` 면 wall-time 은 제품이 아니라 경쟁 프로세스를 잰다. */
export function loadWindow() {
  const cores = os.cpus().length;
  const load1m = os.loadavg()[0];
  return { cores, load1m, threshold: cores * BUSY_FACTOR, busy: load1m > cores * BUSY_FACTOR };
}

/**
 * 건너뛴 이유를 사람이 읽을 한 줄로. **사유 없는 skip 을 만들지 않기 위해** 잰 값을 넣는다
 * (G1 의 「사유 없는 skip 0」과 양립한다 — 사유가 곧 측정 기록이다).
 */
export function busyReason(w, what) {
  return `${what}: 부하 창이라 시간 판정을 하지 않는다 — load1m ${w.load1m.toFixed(2)} > `
    + `${w.cores}코어 × ${BUSY_FACTOR} = ${w.threshold.toFixed(2)}. `
    + '부하가 있으면 wall-time 은 제품이 아니라 경쟁 프로세스를 잰다(CPU 시간·비율도 마찬가지임을 실측했다). '
    + '유휴 창에서 다시 돌려라.';
}
